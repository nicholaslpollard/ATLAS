from packages.ml.dataset_policy import (
    ML_TRAINING_DATASET_ACCEPTED,
    ML_TRAINING_DATASET_ACCEPTED_CLASS_ROWS,
    ML_TRAINING_DATASET_ACCEPTED_DISTINCT_KEYS,
    ML_TRAINING_DATASET_ACCEPTED_ID,
    ML_TRAINING_DATASET_ACCEPTED_LINEAGE_SHA256,
    ML_TRAINING_DATASET_ACCEPTED_MARKET_CONTEXT_FRACTION,
    ML_TRAINING_DATASET_ACCEPTED_MARKET_CONTEXT_ROWS,
    ML_TRAINING_DATASET_ACCEPTED_PARTITION_SHA256,
    ML_TRAINING_DATASET_ACCEPTED_PREDICTOR_COUNT,
    ML_TRAINING_DATASET_ACCEPTED_ROWS,
    ML_TRAINING_DATASET_POLICY_CONTRACT_VERSION,
)
from packages.ml.label_policy import ML_GATE4_ACCEPTED_USABLE_ROWS


def test_phase10_gate6_dataset_policy_locks_verified_dataset() -> None:
    assert ML_TRAINING_DATASET_POLICY_CONTRACT_VERSION == (
        "ml-training-dataset-policy-v1-accepted-f31596905f0c7b7f"
    )
    assert ML_TRAINING_DATASET_ACCEPTED is True
    assert ML_TRAINING_DATASET_ACCEPTED_ID == "mltrain-2026-08-14-f31596905f0c7b7f"
    assert ML_TRAINING_DATASET_ACCEPTED_LINEAGE_SHA256 == (
        "f31596905f0c7b7f6c442df3f99304360706fd922b3179635d64dfc7c9ff8d68"
    )


def test_phase10_gate6_dataset_policy_reconciles_rows_classes_and_predictors() -> None:
    assert ML_TRAINING_DATASET_ACCEPTED_ROWS == ML_GATE4_ACCEPTED_USABLE_ROWS
    assert ML_TRAINING_DATASET_ACCEPTED_DISTINCT_KEYS == ML_TRAINING_DATASET_ACCEPTED_ROWS
    assert ML_TRAINING_DATASET_ACCEPTED_PREDICTOR_COUNT == 33
    assert sum(ML_TRAINING_DATASET_ACCEPTED_CLASS_ROWS.values()) == ML_TRAINING_DATASET_ACCEPTED_ROWS
    assert set(ML_TRAINING_DATASET_ACCEPTED_PARTITION_SHA256) == {2022, 2023, 2024, 2025, 2026}


def test_phase10_gate6_market_context_is_metadata_on_final_labeled_population() -> None:
    assert ML_TRAINING_DATASET_ACCEPTED_MARKET_CONTEXT_ROWS == 5_105_194
    assert ML_TRAINING_DATASET_ACCEPTED_MARKET_CONTEXT_FRACTION == (
        ML_TRAINING_DATASET_ACCEPTED_MARKET_CONTEXT_ROWS
        / ML_TRAINING_DATASET_ACCEPTED_ROWS
    )
    assert 0.77 < ML_TRAINING_DATASET_ACCEPTED_MARKET_CONTEXT_FRACTION < 0.79
